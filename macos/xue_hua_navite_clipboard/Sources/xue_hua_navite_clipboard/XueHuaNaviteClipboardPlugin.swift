import Cocoa
import FlutterMacOS

public class XueHuaNaviteClipboardPlugin: NSObject, FlutterPlugin, ClipboardHostApi {
  private var registrar: FlutterPluginRegistrar?
  private var pollingTimer: DispatchSourceTimer?
  private var pollingIntervalMs: Int = 500
  private var isListening: Bool = false
  private var lastObservedChangeCount: Int = NSPasteboard.general.changeCount

  private static let typeMarkdown = NSPasteboard.PasteboardType("net.daringfireball.markdown")
  private static let typeConcealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
  private static let typeTransient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
  private static let typeAutoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

  public static func register(with registrar: FlutterPluginRegistrar) {
    let instance = XueHuaNaviteClipboardPlugin()
    instance.registrar = registrar
    ClipboardHostApiSetup.register(api: instance, registrar: registrar)
  }

  deinit {
    stopPollingTimer()
  }

  // MARK: - Listening (Lazy on-demand polling timer)

  func startClipboardListening() throws {
    isListening = true
    startPollingTimer()
  }

  func stopClipboardListening() throws {
    isListening = false
    stopPollingTimer()
  }

  private func startPollingTimer() {
    stopPollingTimer()
    lastObservedChangeCount = NSPasteboard.general.changeCount

    let timer = DispatchSource.makeTimerSource(queue: .main)
    timer.schedule(
      deadline: .now() + .milliseconds(pollingIntervalMs),
      repeating: .milliseconds(pollingIntervalMs)
    )
    timer.setEventHandler { [weak self] in
      guard let self = self else { return }
      let current = NSPasteboard.general.changeCount
      if current != self.lastObservedChangeCount {
        self.lastObservedChangeCount = current
        let nowMs = Int64(Date().timeIntervalSince1970 * 1000)
        guard let registrar = self.registrar,
              let flutterApi = ClipboardFlutterApiRegistrar.getInstance(registrar: registrar) else {
          return
        }
        try? flutterApi.onClipboardChanged(
          event: WireClipboardChangeEvent(
            buffer: .general,
            changeCount: Int64(current),
            timestampMs: nowMs
          )
        )
      }
    }
    pollingTimer = timer
    timer.resume()
  }

  private func stopPollingTimer() {
    pollingTimer?.cancel()
    pollingTimer = nil
  }

  // MARK: - Pasteboard Resolution

  private func resolvePasteboard(buffer: WireClipboardBuffer, customName: String?) -> NSPasteboard {
    switch buffer {
    case .macOsFind:
      return NSPasteboard(name: .find)
    case .macOsDrag:
      return NSPasteboard(name: .drag)
    case .macOsFont:
      return NSPasteboard(name: .font)
    case .macOsRuler:
      return NSPasteboard(name: .ruler)
    case .named:
      if let name = customName, !name.isEmpty {
        return NSPasteboard(name: NSPasteboard.Name(name))
      }
      return .general
    case .general, .primarySelection:
      return .general
    }
  }

  // MARK: - ClipboardHostApi

  func writeItems(items: [WireClipboardItem], options: WireClipboardWriteOptions) throws -> Bool {
    guard !items.isEmpty else {
      return false
    }

    let pb = resolvePasteboard(buffer: options.buffer, customName: options.customBufferName)
    let isSensitive = options.isSensitive
    let isTransient = options.isTransient

    pb.clearContents()

    var fileUrls: [NSURL] = []
    var pasteboardItems: [NSPasteboardItem] = []
    // Custom MIME/UTI payloads: NSPasteboardItem + writeObjects can drop non-UTI
    // types on modern macOS, so we apply them with addTypes/setData after.
    var deferredCustom: [(NSPasteboard.PasteboardType, Data)] = []

    for item in items {
      if let files = item.files, !files.isEmpty {
        for filePath in files {
          fileUrls.append(NSURL(fileURLWithPath: filePath))
        }
      }

      let pbItem = NSPasteboardItem()
      var hasItemData = false

      if let plainText = item.plainText {
        pbItem.setString(plainText, forType: .string)
        hasItemData = true
      }
      if let html = item.html {
        pbItem.setString(html, forType: .html)
        hasItemData = true
      }
      if let rtfBytes = item.rtfBytes {
        pbItem.setData(Data(rtfBytes), forType: .rtf)
        hasItemData = true
      }
      if let markdown = item.markdown {
        pbItem.setString(markdown, forType: Self.typeMarkdown)
        if item.plainText == nil {
          pbItem.setString(markdown, forType: .string)
        }
        hasItemData = true
      }
      if let uriStr = item.uri {
        pbItem.setString(uriStr, forType: .URL)
        if item.plainText == nil {
          pbItem.setString(uriStr, forType: .string)
        }
        hasItemData = true
      }
      if let imageBytes = item.imageBytes {
        let rawData = Data(imageBytes)
        if let nsImage = NSImage(data: rawData),
           let tiffData = nsImage.tiffRepresentation,
           let bitmapRep = NSBitmapImageRep(data: tiffData),
           let pngData = bitmapRep.representation(using: .png, properties: [:]) {
          pbItem.setData(pngData, forType: .png)
          pbItem.setData(tiffData, forType: .tiff)
        } else {
          pbItem.setData(rawData, forType: .png)
        }
        hasItemData = true
      }
      if let colorValue = item.colorValue {
        let a = CGFloat((colorValue >> 24) & 0xFF) / 255.0
        let r = CGFloat((colorValue >> 16) & 0xFF) / 255.0
        let g = CGFloat((colorValue >> 8) & 0xFF) / 255.0
        let b = CGFloat(colorValue & 0xFF) / 255.0
        let nsColor = NSColor(srgbRed: r, green: g, blue: b, alpha: a)
        if let colorData = try? NSKeyedArchiver.archivedData(withRootObject: nsColor, requiringSecureCoding: false) {
          pbItem.setData(colorData, forType: .color)
          hasItemData = true
        }
      }
      if let customFormats = item.customFormats {
        for entry in customFormats {
          let pbType = NSPasteboard.PasteboardType(entry.format)
          let data = Data(entry.data)
          pbItem.setData(data, forType: pbType)
          deferredCustom.append((pbType, data))
          hasItemData = true
        }
      }

      if isSensitive {
        pbItem.setData(Data(), forType: Self.typeConcealed)
      }
      if isTransient {
        pbItem.setData(Data(), forType: Self.typeTransient)
        pbItem.setData(Data(), forType: Self.typeAutoGenerated)
      }

      if hasItemData {
        pasteboardItems.append(pbItem)
      }
    }

    var writers: [NSPasteboardWriting] = []
    writers.append(contentsOf: fileUrls)
    writers.append(contentsOf: pasteboardItems)

    if writers.isEmpty {
      return false
    }

    let wrote = pb.writeObjects(writers)

    if !deferredCustom.isEmpty {
      let existing = pb.types ?? []
      let customTypes = deferredCustom.map { $0.0 }
      pb.addTypes(customTypes, owner: nil)
      for (pbType, data) in deferredCustom {
        pb.setData(data, forType: pbType)
      }
      _ = existing
    }

    return wrote
  }

  func readItems(options: WireClipboardReadOptions) throws -> [WireClipboardItem] {
    let pb = resolvePasteboard(buffer: options.buffer, customName: options.customBufferName)
    let requestedCustom = options.requestedCustomFormats

    guard let pbItems = pb.pasteboardItems, !pbItems.isEmpty else {
      return []
    }

    var allFilePaths: [String] = []
    if let fileUrls = pb.readObjects(
      forClasses: [NSURL.self],
      options: [.urlReadingFileURLsOnly: true]
    ) as? [URL] {
      allFilePaths = fileUrls.map { $0.path }
    }

    var results: [WireClipboardItem] = []

    for (index, item) in pbItems.enumerated() {
      let plainText = item.string(forType: .string)
      let html = item.string(forType: .html)

      var rtfBytes: [UInt8]?
      if let rtfData = item.data(forType: .rtf) {
        rtfBytes = [UInt8](rtfData)
      }

      let markdown = item.string(forType: Self.typeMarkdown)

      var uriStr = item.string(forType: .URL)
      if uriStr == nil, let text = plainText?.trimmingCharacters(in: .whitespacesAndNewlines),
         (text.hasPrefix("http://") || text.hasPrefix("https://")) {
        uriStr = text
      }

      var imageBytes: [UInt8]?
      if let pngData = item.data(forType: .png) {
        imageBytes = [UInt8](pngData)
      } else if let tiffData = item.data(forType: .tiff),
                let bitmapRep = NSBitmapImageRep(data: tiffData),
                let pngData = bitmapRep.representation(using: .png, properties: [:]) {
        imageBytes = [UInt8](pngData)
      }

      var colorValue: Int64?
      if let colorData = item.data(forType: .color),
         let nsColor = try? NSKeyedUnarchiver.unarchivedObject(ofClass: NSColor.self, from: colorData),
         let srgb = nsColor.usingColorSpace(.sRGB) {
        let ai = Int64(round(srgb.alphaComponent * 255)) & 0xFF
        let ri = Int64(round(srgb.redComponent * 255)) & 0xFF
        let gi = Int64(round(srgb.greenComponent * 255)) & 0xFF
        let bi = Int64(round(srgb.blueComponent * 255)) & 0xFF
        colorValue = (ai << 24) | (ri << 16) | (gi << 8) | bi
      }

      var customEntries: [WireCustomFormatEntry] = []
      for fmt in requestedCustom {
        let pbType = NSPasteboard.PasteboardType(fmt)
        if let rawData = item.data(forType: pbType) {
          customEntries.append(WireCustomFormatEntry(format: fmt, data: [UInt8](rawData)))
        } else if let rawData = pb.data(forType: pbType) {
          customEntries.append(WireCustomFormatEntry(format: fmt, data: [UInt8](rawData)))
        }
      }

      results.append(
        WireClipboardItem(
          plainText: plainText,
          html: html,
          rtfBytes: rtfBytes,
          markdown: markdown,
          uri: uriStr,
          imageBytes: imageBytes,
          imageMimeType: "image/png",
          files: (index == 0 && !allFilePaths.isEmpty) ? allFilePaths : nil,
          fileCopyMode: .copy,
          colorValue: colorValue,
          customFormats: customEntries.isEmpty ? nil : customEntries
        )
      )
    }

    return results
  }

  func getMetadata(
    target: WireClipboardBufferTarget,
    detectPatterns: Bool
  ) async throws -> WireClipboardMetadata {
    let pb = resolvePasteboard(buffer: target.buffer, customName: target.customBufferName)
    let rawTypes = (pb.types ?? []).map { $0.rawValue }
    let typeSet = Set(pb.types ?? [])

    let hasPlainText = typeSet.contains(.string)
    let hasHtml = typeSet.contains(.html)
    let hasRtf = typeSet.contains(.rtf)
    let hasMarkdown = typeSet.contains(Self.typeMarkdown)
    let hasUri = typeSet.contains(.URL)
    let hasImage = typeSet.contains(.png) || typeSet.contains(.tiff)
    let hasFiles = typeSet.contains(.fileURL) || rawTypes.contains("NSFilenamesPboardType")
    let hasColor = typeSet.contains(.color)

    var detectedPatterns: [WireClipboardDetectedPattern] = []
    if detectPatterns,
       let str = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines) {
      if str.hasPrefix("http://") || str.hasPrefix("https://") {
        detectedPatterns.append(.probableWebUrl)
      }
      if Double(str) != nil {
        detectedPatterns.append(.number)
      }
    }

    return WireClipboardMetadata(
      changeCount: Int64(pb.changeCount),
      timestampMs: nil,
      itemCount: Int64(pb.pasteboardItems?.count ?? 0),
      hasPlainText: hasPlainText,
      hasHtml: hasHtml,
      hasRtf: hasRtf,
      hasMarkdown: hasMarkdown,
      hasUri: hasUri,
      hasImage: hasImage,
      hasFiles: hasFiles,
      hasColor: hasColor,
      rawPlatformFormats: rawTypes,
      detectedPatterns: detectedPatterns
    )
  }

  func getChangeCount(target: WireClipboardBufferTarget) throws -> Int64 {
    let pb = resolvePasteboard(buffer: target.buffer, customName: target.customBufferName)
    return Int64(pb.changeCount)
  }

  func clear(target: WireClipboardBufferTarget) throws -> Bool {
    let pb = resolvePasteboard(buffer: target.buffer, customName: target.customBufferName)
    pb.clearContents()
    return true
  }

  func setPollingInterval(intervalMs: Int64) throws {
    if intervalMs >= 100 {
      pollingIntervalMs = Int(intervalMs)
      if isListening {
        startPollingTimer()
      }
    }
  }
}
