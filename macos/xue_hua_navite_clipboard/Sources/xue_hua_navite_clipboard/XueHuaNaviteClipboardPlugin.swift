import Cocoa
import FlutterMacOS

public class XueHuaNaviteClipboardPlugin: NSObject, FlutterPlugin, FlutterStreamHandler {
  private var eventSink: FlutterEventSink?
  private var pollingTimer: DispatchSourceTimer?
  private var pollingIntervalMs: Int = 500
  private var lastObservedChangeCount: Int = NSPasteboard.general.changeCount

  private static let typeMarkdown = NSPasteboard.PasteboardType("net.daringfireball.markdown")
  private static let typeConcealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
  private static let typeTransient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
  private static let typeAutoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

  public static func register(with registrar: FlutterPluginRegistrar) {
    let methodChannel = FlutterMethodChannel(
      name: "xue_hua_navite_clipboard",
      binaryMessenger: registrar.messenger
    )
    let eventChannel = FlutterEventChannel(
      name: "xue_hua_navite_clipboard/events",
      binaryMessenger: registrar.messenger
    )
    let instance = XueHuaNaviteClipboardPlugin()
    registrar.addMethodCallDelegate(instance, channel: methodChannel)
    eventChannel.setStreamHandler(instance)
  }

  deinit {
    stopPollingTimer()
  }

  // MARK: - FlutterStreamHandler (Lazy on-demand polling timer)

  public func onListen(withArguments arguments: Any?, eventSink events: @escaping FlutterEventSink) -> FlutterError? {
    self.eventSink = events
    startPollingTimer()
    return nil
  }

  public func onCancel(withArguments arguments: Any?) -> FlutterError? {
    stopPollingTimer()
    self.eventSink = nil
    return nil
  }

  private func startPollingTimer() {
    stopPollingTimer()
    lastObservedChangeCount = NSPasteboard.general.changeCount

    let timer = DispatchSource.makeTimerSource(queue: .main)
    timer.schedule(
      deadline: .now() + .milliseconds(pollingIntervalMs),
      repeating: .milliseconds(pollingIntervalMs)
    )
    timer.setEventHandler { [weak self] in
      guard let self = self else { return }
      let current = NSPasteboard.general.changeCount
      if current != self.lastObservedChangeCount {
        self.lastObservedChangeCount = current
        let nowMs = Int64(Date().timeIntervalSince1970 * 1000)
        self.eventSink?([
          "buffer": "general",
          "changeCount": current,
          "timestampMs": nowMs
        ])
      }
    }
    pollingTimer = timer
    timer.resume()
  }

  private func stopPollingTimer() {
    pollingTimer?.cancel()
    pollingTimer = nil
  }

  // MARK: - Pasteboard Resolution

  private func resolvePasteboard(buffer: String?, customName: String?) -> NSPasteboard {
    switch buffer {
    case "macOsFind":
      return NSPasteboard(name: .find)
    case "macOsDrag":
      return NSPasteboard(name: .drag)
    case "macOsFont":
      return NSPasteboard(name: .font)
    case "macOsRuler":
      return NSPasteboard(name: .ruler)
    case "named":
      if let name = customName, !name.isEmpty {
        return NSPasteboard(name: NSPasteboard.Name(name))
      }
      return .general
    default:
      return .general
    }
  }

  // MARK: - MethodCall Handler

  public func handle(_ call: FlutterMethodCall, result: @escaping FlutterResult) {
    let args = call.arguments as? [String: Any]
    switch call.method {
    case "getPlatformVersion":
      result("macOS " + ProcessInfo.processInfo.operatingSystemVersionString)
    case "writeItems":
      result(handleWriteItems(args: args))
    case "readItems":
      result(handleReadItems(args: args))
    case "getMetadata":
      result(handleGetMetadata(args: args))
    case "getChangeCount":
      let pb = resolvePasteboard(
        buffer: args?["buffer"] as? String,
        customName: args?["customBufferName"] as? String
      )
      result(pb.changeCount)
    case "clear":
      let pb = resolvePasteboard(
        buffer: args?["buffer"] as? String,
        customName: args?["customBufferName"] as? String
      )
      pb.clearContents()
      result(true)
    case "setPollingInterval":
      if let intervalMs = args?["intervalMs"] as? Int, intervalMs >= 100 {
        pollingIntervalMs = intervalMs
        if eventSink != nil {
          startPollingTimer()
        }
      }
      result(nil)
    default:
      result(FlutterMethodNotImplemented)
    }
  }

  private func handleWriteItems(args: [String: Any]?) -> Bool {
    guard let rawItems = args?["items"] as? [[String: Any]], !rawItems.isEmpty else {
      return false
    }
    let options = args?["options"] as? [String: Any]
    let pb = resolvePasteboard(
      buffer: options?["buffer"] as? String,
      customName: options?["customBufferName"] as? String
    )
    let isSensitive = options?["isSensitive"] as? Bool ?? false
    let isTransient = options?["isTransient"] as? Bool ?? false

    pb.clearContents()

    var pasteboardObjects: [NSPasteboardWriting] = []

    for item in rawItems {
      // Handle multiple files natively if present
      if let files = item["files"] as? [String], !files.isEmpty {
        for filePath in files {
          let fileUrl = NSURL(fileURLWithPath: filePath)
          pasteboardObjects.append(fileUrl)
        }
      }

      let pbItem = NSPasteboardItem()
      var hasItemData = false

      if let plainText = item["plainText"] as? String {
        pbItem.setString(plainText, forType: .string)
        hasItemData = true
      }
      if let html = item["html"] as? String {
        pbItem.setString(html, forType: .html)
        hasItemData = true
      }
      if let rtfTyped = item["rtfBytes"] as? FlutterStandardTypedData {
        pbItem.setData(rtfTyped.data, forType: .rtf)
        hasItemData = true
      }
      if let markdown = item["markdown"] as? String {
        pbItem.setString(markdown, forType: Self.typeMarkdown)
        if item["plainText"] == nil {
          pbItem.setString(markdown, forType: .string)
        }
        hasItemData = true
      }
      if let uriStr = item["uri"] as? String {
        pbItem.setString(uriStr, forType: .URL)
        if item["plainText"] == nil {
          pbItem.setString(uriStr, forType: .string)
        }
        hasItemData = true
      }
      if let imgTyped = item["imageBytes"] as? FlutterStandardTypedData {
        if let nsImage = NSImage(data: imgTyped.data),
           let tiffData = nsImage.tiffRepresentation,
           let bitmapRep = NSBitmapImageRep(data: tiffData),
           let pngData = bitmapRep.representation(using: .png, properties: [:]) {
          pbItem.setData(pngData, forType: .png)
          pbItem.setData(tiffData, forType: .tiff)
        } else {
          pbItem.setData(imgTyped.data, forType: .png)
        }
        hasItemData = true
      }
      if let colorValue = item["colorValue"] as? Int {
        let a = CGFloat((colorValue >> 24) & 0xFF) / 255.0
        let r = CGFloat((colorValue >> 16) & 0xFF) / 255.0
        let g = CGFloat((colorValue >> 8) & 0xFF) / 255.0
        let b = CGFloat(colorValue & 0xFF) / 255.0
        let nsColor = NSColor(srgbRed: r, green: g, blue: b, alpha: a)
        if let colorData = try? NSKeyedArchiver.archivedData(withRootObject: nsColor, requiringSecureCoding: false) {
          pbItem.setData(colorData, forType: .color)
          hasItemData = true
        }
      }
      if let customFormats = item["customFormats"] as? [String: FlutterStandardTypedData] {
        for (fmtKey, typedData) in customFormats {
          pbItem.setData(typedData.data, forType: NSPasteboard.PasteboardType(fmtKey))
          hasItemData = true
        }
      }

      if isSensitive {
        pbItem.setData(Data(), forType: Self.typeConcealed)
      }
      if isTransient {
        pbItem.setData(Data(), forType: Self.typeTransient)
        pbItem.setData(Data(), forType: Self.typeAutoGenerated)
      }

      if hasItemData {
        pasteboardObjects.append(pbItem)
      }
    }

    if pasteboardObjects.isEmpty {
      return false
    }
    return pb.writeObjects(pasteboardObjects)
  }

  private func handleReadItems(args: [String: Any]?) -> [[String: Any?]] {
    let options = args?["options"] as? [String: Any]
    let pb = resolvePasteboard(
      buffer: options?["buffer"] as? String,
      customName: options?["customBufferName"] as? String
    )
    let requestedCustom = (options?["requestedCustomFormats"] as? [String]) ?? []

    guard let pbItems = pb.pasteboardItems, !pbItems.isEmpty else {
      return []
    }

    // Read all file URLs from the pasteboard
    var allFilePaths: [String] = []
    if let fileUrls = pb.readObjects(
      forClasses: [NSURL.self],
      options: [.urlReadingFileURLsOnly: true]
    ) as? [URL] {
      allFilePaths = fileUrls.map { $0.path }
    }

    var results: [[String: Any?]] = []

    for (index, item) in pbItems.enumerated() {
      let plainText = item.string(forType: .string)
      let html = item.string(forType: .html)

      var rtfBytes: FlutterStandardTypedData?
      if let rtfData = item.data(forType: .rtf) {
        rtfBytes = FlutterStandardTypedData(bytes: rtfData)
      }

      let markdown = item.string(forType: Self.typeMarkdown)

      var uriStr = item.string(forType: .URL)
      if uriStr == nil, let text = plainText?.trimmingCharacters(in: .whitespacesAndNewlines),
         (text.hasPrefix("http://") || text.hasPrefix("https://")) {
        uriStr = text
      }

      var imageBytes: FlutterStandardTypedData?
      if let pngData = item.data(forType: .png) {
        imageBytes = FlutterStandardTypedData(bytes: pngData)
      } else if let tiffData = item.data(forType: .tiff),
                let bitmapRep = NSBitmapImageRep(data: tiffData),
                let pngData = bitmapRep.representation(using: .png, properties: [:]) {
        imageBytes = FlutterStandardTypedData(bytes: pngData)
      }

      var colorValue: Int?
      if let colorData = item.data(forType: .color),
         let nsColor = try? NSKeyedUnarchiver.unarchivedObject(ofClass: NSColor.self, from: colorData),
         let srgb = nsColor.usingColorSpace(.sRGB) {
        let ai = Int(round(srgb.alphaComponent * 255)) & 0xFF
        let ri = Int(round(srgb.redComponent * 255)) & 0xFF
        let gi = Int(round(srgb.greenComponent * 255)) & 0xFF
        let bi = Int(round(srgb.blueComponent * 255)) & 0xFF
        colorValue = (ai << 24) | (ri << 16) | (gi << 8) | bi
      }

      var customMap: [String: FlutterStandardTypedData] = [:]
      for fmt in requestedCustom {
        if let rawData = item.data(forType: NSPasteboard.PasteboardType(fmt)) {
          customMap[fmt] = FlutterStandardTypedData(bytes: rawData)
        }
      }

      results.append([
        "plainText": plainText,
        "html": html,
        "rtfBytes": rtfBytes,
        "markdown": markdown,
        "uri": uriStr,
        "imageBytes": imageBytes,
        "imageMimeType": "image/png",
        "files": (index == 0 && !allFilePaths.isEmpty) ? allFilePaths : nil,
        "fileCopyMode": "copy",
        "colorValue": colorValue,
        "customFormats": customMap
      ])
    }

    return results
  }

  private func handleGetMetadata(args: [String: Any]?) -> [String: Any?] {
    let pb = resolvePasteboard(
      buffer: args?["buffer"] as? String,
      customName: args?["customBufferName"] as? String
    )
    let rawTypes = (pb.types ?? []).map { $0.rawValue }
    let typeSet = Set(pb.types ?? [])

    let hasPlainText = typeSet.contains(.string)
    let hasHtml = typeSet.contains(.html)
    let hasRtf = typeSet.contains(.rtf)
    let hasMarkdown = typeSet.contains(Self.typeMarkdown)
    let hasUri = typeSet.contains(.URL)
    let hasImage = typeSet.contains(.png) || typeSet.contains(.tiff)
    let hasFiles = typeSet.contains(.fileURL) || rawTypes.contains("NSFilenamesPboardType")
    let hasColor = typeSet.contains(.color)

    var detectedPatterns: [String] = []
    if let detect = args?["detectPatterns"] as? Bool, detect,
       let str = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines) {
      if str.hasPrefix("http://") || str.hasPrefix("https://") {
        detectedPatterns.append("probableWebUrl")
      }
      if Double(str) != nil {
        detectedPatterns.append("number")
      }
    }

    return [
      "changeCount": pb.changeCount,
      "timestampMs": nil,
      "itemCount": pb.pasteboardItems?.count ?? 0,
      "hasPlainText": hasPlainText,
      "hasHtml": hasHtml,
      "hasRtf": hasRtf,
      "hasMarkdown": hasMarkdown,
      "hasUri": hasUri,
      "hasImage": hasImage,
      "hasFiles": hasFiles,
      "hasColor": hasColor,
      "rawPlatformFormats": rawTypes,
      "detectedPatterns": detectedPatterns
    ]
  }
}
